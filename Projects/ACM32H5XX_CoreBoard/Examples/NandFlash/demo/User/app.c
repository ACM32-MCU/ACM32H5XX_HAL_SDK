/******************************************************************************
*@brief : APP_FMC_NAND_Test
*@param : none
*@return: none
******************************************************************************/
void APP_FMC_NAND_Test(void)
{
    uint8_t nand_id[5];
    uint32_t page_addr;
    int i;
    uint8_t err_flag;
           
    BSP_FMC_NAND_Init(FMC_NAND);
    HAL_FMC_NAND_FlashReset(&BSP_FMC_NAND_Handle);
    
    /* Read ID */
    HAL_FMC_NAND_FlashGetID(&BSP_FMC_NAND_Handle, nand_id, 5);    
    printfS("Read ChipID: %x %x %x %x %x \n",nand_id[0],nand_id[1],nand_id[2],nand_id[3],nand_id[4]);

	page_addr = 0x0;

    /* Erase Block */
	HAL_FMC_NAND_FlashErase(&BSP_FMC_NAND_Handle, page_addr);
    /* Read 512 bytes with no ecc mode */
	HAL_FMC_NAND_FlashRead(&BSP_FMC_NAND_Handle, page_addr, 0, read_buffer_byte, BCH_ECC_MODE_DIS); 
    
    err_flag = 0;
	for(i = 0; i < BCH_SECTOR_SIZE; i++)
	{
		if(read_buffer_byte[i] != 0xff)
		{
			printf("Erase Error at %d:%x.\n", i, read_buffer_byte[i]);
            err_flag = 1;
		}
	}
    if(err_flag)
    {
        err_flag = 0;
        printfS("Erase one block test FAIL!\n");
    }
    else
        printfS("Erase one block test pass.\n");

    
    /* Read write with no ecc mode */
    HAL_FMC_NAND_FlashReset(&BSP_FMC_NAND_Handle);
    HAL_FMC_NAND_FlashErase(&BSP_FMC_NAND_Handle, page_addr);
    
	HAL_FMC_NAND_Flash_Program(&BSP_FMC_NAND_Handle, page_addr, 0, bch_8bit_data, BCH_ECC_MODE_DIS);
	HAL_FMC_NAND_FlashRead(&BSP_FMC_NAND_Handle, page_addr, 0, read_buffer_byte, BCH_ECC_MODE_DIS);
	for(i = 0; i < BCH_SECTOR_SIZE; i++)
	{
		if(bch_8bit_data[i] != read_buffer_byte[i])
        {
            err_flag = 1;
            printf("Read Error at %d:%x.\n", i, read_buffer_byte[i]);
        }
	} 

    if(err_flag)
    {
        err_flag = 0;
        printfS("Read write with no ecc mode test FAIL!\n");
    }
    else
        printfS("Read write with no ecc mode test pass.\n");  


    /* Read write with ecc mode (correct data)*/
    page_addr = 0x94;
    HAL_FMC_NAND_FlashReset(&BSP_FMC_NAND_Handle);  
    HAL_FMC_NAND_FlashErase(&BSP_FMC_NAND_Handle, page_addr); 
	HAL_FMC_NAND_Reset_ECC_Channel(&BSP_FMC_NAND_Handle); 
    
	HAL_FMC_NAND_Flash_Program(&BSP_FMC_NAND_Handle, page_addr, 0, bch_8bit_data, BCH_ECC_MODE_EN);
	if(HAL_FMC_NAND_FlashRead(&BSP_FMC_NAND_Handle, page_addr, 0, read_buffer_byte, BCH_ECC_MODE_EN))
    {
        err_flag = 1;
        printfS("BCH error occured!\n");
    }
    
    err_flag = 0;
	for(i = 0; i < BCH_SECTOR_SIZE; i++)
	{
		if(bch_8bit_data[i] != read_buffer_byte[i])
        {
            err_flag = 1;
            printf("Read Error at %d:%x.\n", i, read_buffer_byte[i]);
        }
	}
    if(err_flag)
    {
        err_flag = 0;
        printfS("Read write with ecc mode(correct data) test FAIL!\n");
    }
    else
        printfS("Read write with ecc mode(correct data) test pass.\n"); 


    /* Read write with ecc mode (wrong data)*/
    bch_8bit_data[3] = 0x75; //人工造错  2bit
    bch_8bit_data[4] = 0xa7; //人工造错  2bit
    bch_8bit_data[7] = 0x11; //人工造错  1bit
    bch_8bit_data[8] = 0x3d; //人工造错  1bit
    HAL_FMC_NAND_FlashReset(&BSP_FMC_NAND_Handle);
    HAL_FMC_NAND_FlashErase(&BSP_FMC_NAND_Handle, page_addr);
	HAL_FMC_NAND_Reset_ECC_Channel(&BSP_FMC_NAND_Handle);
    
    HAL_FMC_NAND_Flash_Program_NECC_with_ECC_CODE(&BSP_FMC_NAND_Handle, page_addr, 0, bch_8bit_data, bch_8bit_code); //write error data with no_ecc mode
    HAL_FMC_NAND_FlashRead(&BSP_FMC_NAND_Handle, page_addr, 0, read_buffer_byte, BCH_ECC_MODE_EN);

    bch_8bit_data[3] = 0x7f; //变回正确数据
    bch_8bit_data[4] = 0xa1; //变回正确数据
    bch_8bit_data[7] = 0x01; //变回正确数据
    bch_8bit_data[8] = 0x2d; //变回正确数据
	for(i = 0; i < BCH_SECTOR_SIZE; i++)
	{
		if(bch_8bit_data[i] != read_buffer_byte[i])
        {
            err_flag = 1;
            printf("Read Error at %d:%x.\n", i, read_buffer_byte[i]);
            return;
        }
	}
    if(err_flag)
    {
        err_flag = 0;
        printfS("Read write with ecc mode(wrong data) test FAIL!\n");
    }
    else
        printfS("Read write with ecc mode(wrong data) test pass.\n"); 
 

    printfS("\nFMC_NAND test over.\n");    
    
}











